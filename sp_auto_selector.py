import pandas as pd
from ipywidgets import interact, Dropdown, Output, VBox, HBox
from IPython.display import display

# load the dataset
file_path = "/content/Stock Phrase Auto-selector_test.xlsx"
df = pd.read_excel(file_path)

# forward-fill 'Element code' to propagate element labels to subsequent rows
df['Element code'] = df['Element code'].ffill()

# Get unique element codes for the main dropdown (exclude any NaN entries)
elements = [e for e in df['Element code'].unique() if pd.notna(e)]

# Prepare dictionaries for metadata dropdown options and element-to-metadata mapping
metadata_options = {}  # Maps metadata code (e.g., NAT00B1A.1) to a list of its dropdown options
element_metadata = {element: [] for element in elements}  # Maps each element to its metadata (MD1...MDn)

# Populate metadata_options and element_metadata by scanning the DataFrame
for _, row in df.iterrows():
    metadata_code = str(row['Element code.1']) if pd.notna(row['Element code.1']) else ''
    element = row['Element code']

    # Identify metadata rows by the presence of a dot in metadata_code and no External comment
    if pd.notna(element) and '.' in metadata_code and pd.isna(row['External comment']):
        # Parse the 'Drop downn values' for this metadata into a list of options
        options_str = str(row['Drop downn values']) if pd.notna(row['Drop downn values']) else ''
        options = [opt.strip() for opt in options_str.split('/') if opt.strip()]
        metadata_options[metadata_code] = options
        element_metadata[element].append(metadata_code)

# Build a logic map for each element, each entry has logics and a corresponding stock phrase
logic_map = {}
for element in elements:
    logic_map[element] = []
    # Filter rows for this element that have a score (Met/Unmet/Not Applicable) and a stock phrase
    logic_rows = df[(df['Element code'] == element) & pd.notna(df['External comment']) & pd.notna(df['Met/Unmet'])]

    for _, row in logic_rows.iterrows():
        logic_str = str(row['Scoring logics']) if pd.notna(row['Scoring logics']) else ''
        phrase_text = str(row['External comment'])
        conditions = []

        if logic_str:
            # Normalize the logic string and split into individual conditions
            logic_line = logic_str.replace('\n', ' ').strip()
            logic_line = logic_line.replace('NOT EQUAL TO', '!=').replace('<>', '!=')
            cond_parts = [part.strip() for part in logic_line.split('AND') if part.strip()]

            for cond in cond_parts:
                if '!=' in cond:
                    code, val = cond.split('!=')
                    code = code.strip()
                    val = val.strip().strip('"')
                    conditions.append((code, val, False))  # False -> value should NOT equal val
                elif '=' in cond:
                    code, val = cond.split('=')
                    code = code.strip()
                    val = val.strip().strip('"')
                    conditions.append((code, val, True))  # True -> value should equal val

        # Add this logic entry (conditions and phrase) to the map
        logic_map[element].append({
            'conditions': conditions,
            'phrase': phrase_text,
            'outcome': row['Met/Unmet']
        })

# Create interactive widgets: element dropdown, metadata dropdown, output area
element_dropdown = Dropdown(options=["Select an Element"] + list(elements), description="Element:", value="Select an Element")
md_container = HBox()  # This will hold metadata dropdowns dynamically for the selected element
output_area = Output()  # To display the resulting stock phrase

# Function to update the stock phrase based on current selections
def update_stock_phrase():
    output_area.clear_output()
    element = element_dropdown.value
    if not element:
        return  # Do nothing if no element is selected

    # Build a dict of current metadata selections
    current_values = {}
    metadata_list = element_metadata.get(element, [])
    for idx, dd in enumerate(md_container.children):
        if idx < len(metadata_list):
            metadata_code = metadata_list[idx]
            current_values[metadata_code] = dd.value

    # Find the first logic entry where all conditions are satisfied
    selected_phrase = None
    for entry in logic_map.get(element, []):
        conds = entry['conditions']
        match = True
        for code, req_val, must_equal in conds:
            val = current_values.get(code)
            if must_equal:
                # Condition requires the metadata's value to equal req_val
                if val != req_val:
                    match = False
                    break
            else:
                # Condition requires the metadata's value to NOT equal req_val
                if val == req_val:
                    match = False
                    break
        if match:
            selected_phrase = entry['phrase']
            break

    # Output the selected phrase or a default message if no match found
    with output_area:
        if selected_phrase:
            print(selected_phrase)
        else:
            print("No stock phrase available for the selected combination.")

# Callback for when the selected element changes
def on_element_change(change):
    if change['name'] == 'value' and change['type'] == 'change':
        selected_element = change['new']
        # Clear any existing metadata dropdowns
        md_container.children = ()
        if selected_element:
            # Create dropdowns for each metadata code (MD1 ... MDn) of the selected element
            metadata_codes = element_metadata.get(selected_element, [])
            md_dropdowns = []
            for i, metadata_code in enumerate(metadata_codes, start=1):
                options = metadata_options.get(metadata_code, [])
                md_dd = Dropdown(options=options, description=f"MD{i}:")
                md_dd.observe(lambda change: update_stock_phrase(), names='value')
                md_dropdowns.append(md_dd)
            # Update the md container with the new metadata dropdowns
            md_container.children = tuple(md_dropdowns)
            # Update the stock phrase output based on the default selections of the new dropdowns
            update_stock_phrase()
        else:
            # If no element selected, clear the output
            output_area.clear_output()

# Attach the observer to the element dropdown
element_dropdown.observe(on_element_change, names='value')

# Display the UI components (Element selector, metadata selectors, output area)
display(VBox([element_dropdown, md_container, output_area]))